import { indexNodes } from '../domain/graph';
import type { GraphData, GraphEdge, GraphNode } from '../domain/schema';

function edgeLine(edge: GraphEdge, nodes: Map<string, GraphNode>) {
  const source = nodes.get(edge.source)?.label ?? edge.source;
  const target = nodes.get(edge.target)?.label ?? edge.target;
  return `- **${source}** —*${edge.relation}*→ **${target}**: ${edge.transition_note} _(confidence ${edge.confidence.toFixed(2)})_\n  - Evidence: ${edge.evidence}`;
}

export function buildClusterMarkdown(graph: GraphData, clusterId: string) {
  const cluster = graph.nodes.find((node) => node.id === clusterId);
  if (!cluster || cluster.type !== 'cluster') throw new Error('Select a valid cluster.');
  const nodes = indexNodes(graph);
  const members = graph.nodes.filter(
    (node) => node.cluster === clusterId && node.status !== 'rejected',
  );
  const memberIds = new Set(members.map((node) => node.id));
  const edges = graph.edges.filter(
    (edge) =>
      edge.status !== 'rejected' &&
      (memberIds.has(edge.source) || memberIds.has(edge.target)),
  );
  const papers = members.filter((node) => node.type === 'paper');
  const concepts = members.filter((node) => node.type !== 'paper');

  const lines = [
    `# Literature Notes: ${cluster.label}`,
    '',
    `> Generated by LitBench on ${new Date().toISOString().slice(0, 10)} · \`${clusterId}\` · ${papers.length} papers`,
    '',
    '## Overview',
    '',
    cluster.description ?? '',
    cluster.notes ?? '',
    '',
    '## Papers',
  ];

  for (const node of papers) {
    const paper = node.paper!;
    lines.push(
      '',
      `### ${paper.title}`,
      `*${paper.venue} · ${paper.year}*`,
      paper.authors.join(', '),
      `<${paper.url}>`,
      '',
      paper.summary,
      '',
      'Key findings:',
      ...paper.key_findings.map((finding) => `- ${finding}`),
      ...(node.notes ? ['', 'Personal notes:', node.notes] : []),
    );
  }
  if (concepts.length) {
    lines.push(
      '',
      '## Concepts',
      '',
      ...concepts.map(
        (node) =>
          `- **${node.label}**${node.description ? `: ${node.description}` : ''}${node.notes ? `\n\n${node.notes}` : ''}`,
      ),
    );
  }
  if (edges.length) {
    lines.push('', '## Connections', '', ...edges.map((edge) => edgeLine(edge, nodes)));
  }
  lines.push('');
  return lines.join('\n');
}

export function downloadText(filename: string, content: string, type = 'text/markdown') {
  const url = URL.createObjectURL(new Blob([content], { type }));
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  link.remove();
  URL.revokeObjectURL(url);
}
